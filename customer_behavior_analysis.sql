1.--What is the total revenue generated by male vs. female customers?

SELECT "Gender",
       SUM("Purchase Amount (USD)") AS revenue
FROM customer
GROUP BY "Gender";

2.--Which customers used a discount but still spent more than the average purchase amount?
SELECT
    "Customer ID",
    "Purchase Amount (USD)"
FROM customer
WHERE "Discount Applied" = 'Yes'
AND "Purchase Amount (USD)" > (
    SELECT AVG("Purchase Amount (USD)")
    FROM customer
);

3.-- Which are the top 5 products with the highest average review rating?
SELECT
    "Item Purchased",
    ROUND(AVG("Review Rating")::numeric, 2) AS average_rating
FROM customer
GROUP BY "Item Purchased"
ORDER BY average_rating DESC
LIMIT 20;

-- 4. Compare the average Purchase Amounts between Standard and Express Shipping. 

SELECT
    "Shipping Type",
    ROUND(AVG("Purchase Amount (USD)")::numeric, 2) AS average_purchase_amount
FROM customer
WHERE "Shipping Type" IN ('Standard', 'Express')
GROUP BY "Shipping Type"
ORDER BY average_purchase_amount DESC;

5.--Do subscribed customers spend more? Compare average spend and total revenue 
   --between subscribers and non-subscribers.

SELECT
    "Subscription Status",
    COUNT(*) AS total_customers,
    ROUND(AVG("Purchase Amount (USD)")::numeric, 2) AS average_spend,
    SUM("Purchase Amount (USD)") AS total_revenue
FROM customer
GROUP BY "Subscription Status"
ORDER BY average_spend DESC;

--Q6. Which 5 products have the highest percentage of purchases with discounts applied?

SELECT
    "Item Purchased",
    COUNT(*) AS total_purchases,
    SUM(CASE WHEN "Discount Applied" = 'Yes' THEN 1 ELSE 0 END) AS discounted_purchases,
    ROUND(
        100.0 * SUM(CASE WHEN "Discount Applied" = 'Yes' THEN 1 ELSE 0 END) / COUNT(*),
        2
    ) AS discount_percentage
FROM customer
GROUP BY "Item Purchased"
ORDER BY discount_percentage DESC
LIMIT 20;

--Q7. Segment customers into New, Returning, and Loyal based on their total 
-- number of previous purchases, and show the count of each segment. 

WITH customer_segment AS (
    SELECT
        "Customer ID",
        CASE
            WHEN "Previous Purchases" = 1 THEN 'New'
            WHEN "Previous Purchases" BETWEEN 2 AND 10 THEN 'Returning'
            ELSE 'Loyal'
        END AS customer_segment
    FROM customer
)
SELECT
    customer_segment,
    COUNT(*) AS number_of_customers
FROM customer_segment
GROUP BY customer_segment

--Q8. What are the top 3 most purchased products within each category? 

WITH product_counts AS (
    SELECT
        "Category",
        "Item Purchased",
        COUNT(*) AS total_purchases,
        ROW_NUMBER() OVER (
            PARTITION BY "Category"
            ORDER BY COUNT(*) DESC, "Item Purchased"
        ) AS item_rank
    FROM customer
    GROUP BY "Category", "Item Purchased"
)
SELECT
    item_rank,
    "Category",
    "Item Purchased",
    total_purchases
FROM product_counts
WHERE item_rank <= 3
ORDER BY "Category", item_rank;

--Q9. Are customers who are repeat buyers (more than 5 previous purchases) also likely to subscribe?

SELECT
    CASE
        WHEN "Previous Purchases" > 5 THEN 'Repeat Buyer (>5)'
        ELSE 'Non-Repeat Buyer (<=5)'
    END AS buyer_type,
    COUNT(*) AS total_customers,
    SUM(CASE WHEN "Subscription Status" = 'Yes' THEN 1 ELSE 0 END) AS subscribed_customers,
    ROUND(
        100.0 * SUM(CASE WHEN "Subscription Status" = 'Yes' THEN 1 ELSE 0 END) / COUNT(*),
        2
    ) AS subscription_rate_pct
FROM customer
GROUP BY buyer_type
ORDER BY subscription_rate_pct DESC;


--Q10. What is the revenue contribution of each age group? 

WITH age_groups AS (
    SELECT
        CASE
            WHEN "Age" BETWEEN 18 AND 25 THEN '18-25'
            WHEN "Age" BETWEEN 26 AND 35 THEN '26-35'
            WHEN "Age" BETWEEN 36 AND 45 THEN '36-45'
            WHEN "Age" BETWEEN 46 AND 55 THEN '46-55'
            WHEN "Age" BETWEEN 56 AND 65 THEN '56-65'
            ELSE '65+'
        END AS age_group,
        "Purchase Amount (USD)" AS purchase_amount
    FROM customer
)
SELECT
    age_group,
    SUM(purchase_amount) AS total_revenue,
    ROUND(
        100.0 * SUM(purchase_amount) / SUM(SUM(purchase_amount)) OVER (),
        2
    ) AS revenue_contribution_pct
FROM age_groups
GROUP BY age_group
ORDER BY total_revenue DESC;
